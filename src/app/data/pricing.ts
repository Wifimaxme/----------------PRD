/**
 * Единственный источник правды по ценам на сайте.
 *
 * Сверено с MoyKlass 2026-08-20 по фактическим счетам за 2026-01-30…2026-08-19
 * (1500 последних из 6457): 2760 ₽ — 925 счетов, 1960 ₽ — 372 счёта.
 *
 * Что откуда берётся:
 * - `base` совпадает с полем `price` абонемента id=120733 в CRM
 *   (GET /v1/company/subscriptions). Его при желании можно тянуть по API.
 * - `privileged` в API недоступна: раздел скидок MoyKlass наружу не отдаёт
 *   (GET /v1/company/discounts → 404), а отдельного льготного абонемента нет
 *   и не будет — льгота считается скидкой от базового абонемента.
 *   Поэтому льготную цену держим здесь и правим руками вслед за CRM.
 *
 * Разница между тарифами не сводится к устойчивому правилу: сейчас это 800 ₽
 * (100 ₽ с занятия), а в сезоне 2024/25 при ценах 2560/1820 было 740 ₽.
 * Поэтому льготную цену задаём числом, а не вычисляем из базовой.
 */
export const PRICING = {
    /** Обычный тариф, ₽/месяц. */
    base: 2760,
    /** Льготный тариф, ₽/месяц: многодетные, опекуны, сотрудники ДОУ, 2+ детей. */
    privileged: 1960,
    /** Занятий в абонементе — из него считается стоимость одного занятия. */
    visitsPerSubscription: 8,
} as const;

/** «2760» → «2 760». Разряды разделяем обычным пробелом, как было в вёрстке. */
export function formatPrice(amount: number): string {
    return String(amount).replace(/\B(?=(\d{3})+(?!\d))/g, ' ');
}
